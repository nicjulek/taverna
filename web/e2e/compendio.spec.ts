import { expect, test } from '@playwright/test'
import { newPlayer, signUp } from './helpers'

test('compêndio com SRD, homebrew do mestre e magia levada para a ficha', async ({ browser }) => {
  const gm = await newPlayer(browser, 'Mestra')
  await gm.goto('/criar-conta')
  await signUp(gm, 'Mestra')
  await gm.getByRole('button', { name: 'Nova campanha' }).first().click()
  await gm.getByLabel('Nome').fill('Torre do Sábio')
  await gm.getByRole('button', { name: 'Criar campanha' }).click()
  await gm.getByRole('link', { name: 'Jogadores' }).click()
  const invite = await gm.locator('[title*="/convite/"]').getAttribute('title')

  await gm.getByRole('link', { name: 'Compêndio' }).click()
  await gm.getByRole('button', { name: 'Magias', exact: true }).click()
  await gm.getByRole('combobox', { name: 'Círculo' }).click()
  await gm.getByRole('option', { name: '3º círculo' }).click()
  await gm.getByLabel('Procurar no compêndio').fill('fireb')
  await gm.getByRole('link', { name: /Fireball/ }).click()
  await expect(gm.getByRole('heading', { name: 'Fireball' })).toBeVisible()
  await expect(gm.getByText('3º: 8d6')).toBeVisible()

  await gm.getByRole('button', { name: 'Monstros', exact: true }).click()
  await gm.getByLabel('Procurar no compêndio').fill('goblin')
  await gm.getByRole('link', { name: /^Goblin/ }).click()
  await gm.getByRole('button', { name: 'Ataque +4' }).first().click()
  await expect(gm.getByText(/Goblin · Scimitar: \d+/)).toBeVisible()

  await gm.getByRole('button', { name: 'Novo homebrew' }).click()
  await gm.getByRole('combobox', { name: 'Tipo' }).click()
  await gm.getByRole('option', { name: 'Magia' }).click()
  await gm.getByLabel('Nome', { exact: true }).fill('Lança de Brasa')
  await gm.getByLabel('Dano (opcional)').fill('3d8')
  await gm.getByLabel('Publicar para o grupo').check()
  await gm.getByRole('button', { name: 'Salvar e publicar' }).click()
  await expect(gm.getByRole('heading', { name: 'Lança de Brasa' })).toBeVisible()

  const player = await newPlayer(browser, 'Maga', { width: 390, height: 844 })
  await player.goto(invite!)
  await signUp(player, 'Maga')
  await player.getByRole('button', { name: 'Entrar na campanha' }).click()
  await player.getByRole('link', { name: 'Dados' }).click()
  await expect(player.getByRole('heading', { name: 'Nenhum dado rolado ainda' })).toBeVisible()

  await player.getByRole('link', { name: 'Fichas' }).click()
  await player.getByRole('button', { name: 'Nova ficha' }).click()
  await player.getByLabel('Nome do personagem').fill('Ilsa')
  await player.getByRole('combobox', { name: 'Classe' }).click()
  await player.getByRole('option', { name: 'Mago' }).click()
  await player.getByRole('button', { name: 'Criar ficha' }).click()
  await player.getByRole('button', { name: 'Compêndio' }).click()
  await player.getByLabel('Procurar no compêndio').fill('lança de')
  await player.getByRole('button', { name: 'Adicionar Lança de Brasa à ficha' }).click()
  await player.getByLabel('Procurar no compêndio').fill('fire bolt')
  await player.getByRole('button', { name: 'Adicionar Fire Bolt à ficha' }).click()
  await player.getByRole('button', { name: 'Fechar compêndio' }).click()
  await expect(player.getByRole('tab', { name: 'Magias' })).toHaveAttribute('aria-selected', 'true')
  await expect(player.getByRole('tabpanel').getByText('Lança de Brasa')).toBeVisible()
  await expect(player.getByRole('tabpanel').getByText('Fire Bolt')).toBeVisible()
  await expect(player.getByText('Tudo salvo')).toBeVisible()
})
