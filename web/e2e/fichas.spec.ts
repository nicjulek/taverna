import { expect, test } from '@playwright/test'
import { newPlayer, signUp } from './helpers'

test('jogadora cria a ficha, rola da ficha e o mestre acompanha', async ({ browser }) => {
  const gm = await newPlayer(browser, 'Mestra')
  await gm.goto('/criar-conta')
  await signUp(gm, 'Mestra')
  await gm.getByRole('button', { name: 'Nova campanha' }).first().click()
  await gm.getByLabel('Nome').fill('Ilha das Brumas')
  await gm.getByRole('button', { name: 'Criar campanha' }).click()
  await gm.getByRole('link', { name: 'Jogadores' }).click()
  const invite = await gm.locator('[title*="/convite/"]').getAttribute('title')

  const player = await newPlayer(browser, 'Ladina', { width: 390, height: 844 })
  await player.goto(invite!)
  await signUp(player, 'Ladina')
  await player.getByRole('button', { name: 'Entrar na campanha' }).click()
  await player.getByRole('link', { name: 'Fichas' }).click()
  await expect(player.getByRole('heading', { name: 'Nenhuma ficha ainda' })).toBeVisible()
  await player.getByRole('button', { name: 'Nova ficha' }).click()
  await player.getByLabel('Nome do personagem').fill('Nix')
  await player.getByRole('combobox', { name: 'Classe' }).click()
  await player.getByRole('option', { name: 'Ladino', exact: true }).click()
  await player.getByLabel('Nível').fill('5')
  await player.getByRole('button', { name: 'Criar ficha' }).click()

  await expect(player.getByLabel('Nome do personagem')).toHaveValue('Nix')
  await player.getByLabel('Valor de Destreza').fill('18')
  await player.getByLabel('Valor de Destreza').press('Enter')
  await player.getByRole('button', { name: 'Furtividade: sem proficiência. Trocar' }).click()
  await player.getByRole('button', { name: 'Furtividade: proficiente. Trocar' }).click()
  await expect(player.getByRole('button', { name: 'Rolar Furtividade +10' })).toBeVisible()
  await expect(player.getByText('Tudo salvo')).toBeVisible()

  await gm.getByRole('link', { name: 'Fichas' }).click()
  await gm.getByRole('link', { name: /Nix/ }).click()
  await expect(gm.getByRole('button', { name: 'Rolar Furtividade +10' })).toBeVisible()
  await gm.getByRole('link', { name: 'Dados' }).click()

  await player.getByRole('button', { name: 'Vantagem', exact: true }).click()
  await player.getByRole('button', { name: 'Rolar Furtividade +10' }).click()
  const card = gm.getByRole('article', { name: /Ladina, Nix: Furtividade/ })
  await expect(card).toBeVisible()
  await expect(card.getByText('2d20kh1')).toBeVisible()
  await expect(player.getByRole('button', { name: 'Normal', exact: true })).toHaveAttribute('aria-pressed', 'true')

  await player.getByLabel('Quantidade de dano ou cura').fill('999')
  await player.getByRole('button', { name: 'Dano', exact: true }).click()
  await expect(player.getByText('Testes contra a morte')).toBeVisible()
  await player.getByRole('button', { name: 'Descanso longo' }).click()
  await expect(player.getByText('Testes contra a morte')).toHaveCount(0)
  await expect(player.getByLabel(/Pontos de vida \d+ de \d+/)).toBeVisible()

  await player.getByRole('tab', { name: 'Recursos' }).click()
  await player.getByLabel('Nome do contador').fill('Cargas da varinha')
  await player.getByRole('button', { name: 'Adicionar', exact: true }).click()
  await player.getByRole('button', { name: 'Cargas da varinha 1, disponível' }).click()
  await expect(player.getByRole('group', { name: 'Cargas da varinha: 2 de 3 disponíveis' })).toBeVisible()
  await expect(player.getByText('Tudo salvo')).toBeVisible()

  await gm.getByRole('link', { name: 'Fichas' }).click()
  await gm.getByRole('link', { name: /Nix/ }).click()
  await gm.getByRole('tab', { name: 'Recursos' }).click()
  await expect(gm.getByRole('group', { name: 'Cargas da varinha: 2 de 3 disponíveis' })).toBeVisible()
})

test('outra jogadora só lê a ficha alheia', async ({ browser }) => {
  const owner = await newPlayer(browser, 'Dona')
  await owner.goto('/criar-conta')
  await signUp(owner, 'Dona')
  await owner.getByRole('button', { name: 'Nova campanha' }).first().click()
  await owner.getByLabel('Nome').fill('Teste de leitura')
  await owner.getByRole('button', { name: 'Criar campanha' }).click()
  await owner.getByRole('link', { name: 'Jogadores' }).click()
  const invite = await owner.locator('[title*="/convite/"]').getAttribute('title')

  const reader = await newPlayer(browser, 'Leitora')
  await reader.goto(invite!)
  await signUp(reader, 'Leitora')
  await reader.getByRole('button', { name: 'Entrar na campanha' }).click()
  await reader.getByRole('link', { name: 'Fichas' }).click()
  await reader.getByRole('button', { name: 'Nova ficha' }).click()
  await reader.getByLabel('Nome do personagem').fill('Bram')
  await reader.getByRole('button', { name: 'Criar ficha' }).click()
  await expect(reader.getByText('Tudo salvo')).toBeVisible()
  const url = reader.url()

  const other = await newPlayer(browser, 'Curiosa')
  await other.goto(invite!)
  await signUp(other, 'Curiosa')
  await other.getByRole('button', { name: 'Entrar na campanha' }).click()
  await other.goto(new URL(url).pathname)
  await expect(other.getByRole('heading', { name: 'Bram' })).toBeVisible()
  await expect(other.getByRole('button', { name: /Rolar/ })).toHaveCount(0)
  await expect(other.getByLabel('Valor de Força')).toHaveCount(0)
})
