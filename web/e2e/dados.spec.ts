import { expect, test } from '@playwright/test'
import { newPlayer, signUp } from './helpers'

test('rolagens aparecem na hora para a mesa, e as secretas só para quem pode ver', async ({ browser }) => {
  const gm = await newPlayer(browser, 'Mestra')
  await gm.goto('/criar-conta')
  await signUp(gm, 'Mestra')
  await gm.getByRole('button', { name: 'Nova campanha' }).first().click()
  await gm.getByLabel('Nome').fill('Pântano Sombrio')
  await gm.getByRole('button', { name: 'Criar campanha' }).click()
  await gm.getByRole('link', { name: 'Jogadores' }).click()
  const invite = await gm.locator('[title*="/convite/"]').getAttribute('title')

  const player = await newPlayer(browser, 'Guerreira', { width: 390, height: 844 })
  await player.goto(invite!)
  await signUp(player, 'Guerreira')
  await player.getByRole('button', { name: 'Entrar na campanha' }).click()
  await player.getByRole('link', { name: 'Chat e dados' }).click()
  await gm.getByRole('link', { name: 'Chat e dados' }).click()
  await expect(gm.getByText('Ninguém falou nada ainda')).toBeVisible()

  const formula = player.getByLabel('Rolagem', { exact: true })
  await player.getByRole('button', { name: 'Limpar' }).click()
  await player.getByRole('button', { name: 'Adicionar um d6' }).click()
  await player.getByRole('button', { name: 'Adicionar um d6' }).click()
  await player.getByRole('button', { name: 'Aumentar modificador' }).click()
  await expect(formula).toHaveValue('2d6 + 1')
  await expect(player.getByText('de 3 a 13, média 8')).toBeVisible()
  await expect(player.getByRole('button', { name: 'Vantagem', exact: true })).toBeDisabled()

  await formula.fill('1d20+4')
  await player.getByRole('button', { name: 'Vantagem', exact: true }).click()
  await player.getByLabel('O que é? (opcional)').fill('Ataque com machado')
  await player.getByRole('button', { name: 'Rolar', exact: true }).click()

  const card = gm.getByRole('article', { name: /Guerreira, Ataque com machado/ })
  await expect(card).toBeVisible()
  await expect(card.getByText('2d20kh1')).toBeVisible()

  await formula.fill('1d20+2')
  await player.getByLabel('O que é? (opcional)').fill('Furtividade')
  await player.getByRole('combobox', { name: 'Quem vê a rolagem' }).click()
  await player.getByRole('option', { name: 'Eu e os mestres' }).click()
  await player.getByRole('button', { name: 'Rolar', exact: true }).click()
  await expect(player.getByRole('article', { name: /Furtividade/ }).getByText('Eu e os mestres')).toBeVisible()
  await expect(gm.getByRole('article', { name: /Furtividade/ })).toBeVisible()

  await gm.getByLabel('Rolagem', { exact: true }).fill('1d20+')
  await expect(gm.getByText('A rolagem terminou no meio')).toBeVisible()
  await expect(gm.getByRole('button', { name: 'Rolar', exact: true })).toBeDisabled()
  await gm.getByLabel('Rolagem', { exact: true }).fill('1d20 # Emboscada')
  await gm.getByRole('combobox', { name: 'Quem vê a rolagem' }).click()
  await gm.getByRole('option', { name: 'Só eu' }).click()
  await gm.getByRole('button', { name: 'Rolar', exact: true }).click()
  await expect(gm.getByRole('article', { name: /Emboscada/ })).toBeVisible()
  await player.waitForTimeout(500)
  await expect(player.getByRole('article', { name: /Emboscada/ })).toHaveCount(0)

  await player.getByRole('link', { name: 'Diário' }).click()
  await gm.getByLabel('Rolagem', { exact: true }).fill('1d8')
  await gm.getByLabel('O que é? (opcional)').fill('')
  await gm.getByRole('combobox', { name: 'Quem vê a rolagem' }).click()
  await gm.getByRole('option', { name: 'Todos veem' }).click()
  await gm.getByRole('button', { name: 'Rolar', exact: true }).click()
  await expect(player.getByText(/Mestra rolou \d+/)).toBeVisible()
})
